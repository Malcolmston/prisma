package prisma

import (
	"fmt"
	"reflect"
	"strings"
	"sync"
)

// TableNamer lets a model type override the table name derived from its Go
// type name. Implement it on the struct (value or pointer receiver) to control
// the exact table used in generated SQL.
type TableNamer interface {
	TableName() string
}

// Field describes a single mapped struct field. A Field is either a column
// (Relation == nil) or a relation to another model (Relation != nil).
type Field struct {
	// GoName is the exported Go struct field name.
	GoName string
	// Column is the SQL column name (empty for relation fields).
	Column string
	// Index is the reflect field index path used to read/write the value.
	Index []int
	// IsPK reports whether this column is the primary key.
	IsPK bool
	// IsAuto reports whether the database generates this column's value, in
	// which case it is omitted from INSERT statements.
	IsAuto bool
	// Relation, when non-nil, describes a link to another model.
	Relation *Relation
}

// Relation describes a to-one or to-many link between two models.
type Relation struct {
	// Target is the related struct type (with pointer/slice stripped).
	Target reflect.Type
	// ForeignKey is the column on the owning model.
	ForeignKey string
	// References is the column on the target model (defaults to its PK).
	References string
	// Many reports whether the relation is a collection (slice field).
	Many bool
}

// Model is the compiled schema for a Go struct: its table, columns, primary
// key and relations. Models are produced by a Registry.
type Model struct {
	// Name is the Go type name.
	Name string
	// Table is the SQL table name.
	Table string
	// Type is the underlying struct type.
	Type reflect.Type
	// Fields holds the column fields in declaration order.
	Fields []*Field
	// Relations holds the relation fields in declaration order.
	Relations []*Field
	// PK is the primary-key field, or nil if none was found.
	PK *Field

	colByName map[string]*Field
	colByCol  map[string]*Field
	relByName map[string]*Field
}

// Columns returns the SQL column names in declaration order.
func (m *Model) Columns() []string {
	cols := make([]string, len(m.Fields))
	for i, f := range m.Fields {
		cols[i] = f.Column
	}
	return cols
}

// FieldByColumn returns the column field with the given SQL name.
func (m *Model) FieldByColumn(col string) (*Field, bool) {
	f, ok := m.colByCol[col]
	return f, ok
}

// Relation returns the relation field with the given Go field name.
func (m *Model) RelationByName(name string) (*Field, bool) {
	f, ok := m.relByName[name]
	return f, ok
}

// Registry stores compiled models and lets them be resolved by type or name.
// The zero value is not usable; construct one with NewRegistry.
type Registry struct {
	mu     sync.RWMutex
	byType map[reflect.Type]*Model
	byName map[string]*Model
}

// NewRegistry returns an empty registry.
func NewRegistry() *Registry {
	return &Registry{
		byType: map[reflect.Type]*Model{},
		byName: map[string]*Model{},
	}
}

// Register compiles the schema for v (a struct or pointer to struct) via
// reflection and struct tags, stores it, and returns the model. Re-registering
// the same type returns the previously compiled model.
//
// Struct tags use the key "prisma" with comma-separated options:
//
//	col=<name>    explicit column name (default: snake_case of the field)
//	pk            marks the primary key
//	auto          value is generated by the DB (skipped on INSERT)
//	-             skip the field entirely
//	relation      the field links to another model
//	fk=<col>      relation: foreign-key column on this model
//	references=<col> relation: referenced column on the target (default: its PK)
//
// A field whose type is a pointer-to-struct or slice-of-struct and is tagged
// "relation" becomes a relation rather than a column.
func (r *Registry) Register(v any) (*Model, error) {
	t := reflect.TypeOf(v)
	if t == nil {
		return nil, fmt.Errorf("prisma: cannot register nil")
	}
	for t.Kind() == reflect.Pointer {
		t = t.Elem()
	}
	if t.Kind() != reflect.Struct {
		return nil, fmt.Errorf("prisma: cannot register %s: not a struct", t.Kind())
	}

	r.mu.RLock()
	if m, ok := r.byType[t]; ok {
		r.mu.RUnlock()
		return m, nil
	}
	r.mu.RUnlock()

	m, err := compileModel(t, v)
	if err != nil {
		return nil, err
	}

	r.mu.Lock()
	defer r.mu.Unlock()
	if existing, ok := r.byType[t]; ok {
		return existing, nil
	}
	r.byType[t] = m
	r.byName[m.Name] = m
	return m, nil
}

// ModelOf returns the compiled model for the given type, if registered.
func (r *Registry) ModelOf(t reflect.Type) (*Model, bool) {
	for t.Kind() == reflect.Pointer {
		t = t.Elem()
	}
	r.mu.RLock()
	defer r.mu.RUnlock()
	m, ok := r.byType[t]
	return m, ok
}

func compileModel(t reflect.Type, v any) (*Model, error) {
	m := &Model{
		Name:      t.Name(),
		Type:      t,
		colByName: map[string]*Field{},
		colByCol:  map[string]*Field{},
		relByName: map[string]*Field{},
	}
	m.Table = tableName(t, v)

	for i := 0; i < t.NumField(); i++ {
		sf := t.Field(i)
		if !sf.IsExported() {
			continue
		}
		tag := sf.Tag.Get("prisma")
		opts := parseTag(tag)
		if opts.skip {
			continue
		}

		if opts.relation {
			rel, err := buildRelation(sf, opts)
			if err != nil {
				return nil, fmt.Errorf("prisma: %s.%s: %w", t.Name(), sf.Name, err)
			}
			f := &Field{GoName: sf.Name, Index: sf.Index, Relation: rel}
			m.Relations = append(m.Relations, f)
			m.relByName[sf.Name] = f
			continue
		}

		col := opts.col
		if col == "" {
			col = snakeCase(sf.Name)
		}
		f := &Field{
			GoName: sf.Name,
			Column: col,
			Index:  sf.Index,
			IsPK:   opts.pk,
			IsAuto: opts.auto,
		}
		if f.IsPK && !opts.autoSet {
			// Integer primary keys default to auto-generated.
			if isIntKind(sf.Type.Kind()) {
				f.IsAuto = true
			}
		}
		m.Fields = append(m.Fields, f)
		m.colByName[sf.Name] = f
		m.colByCol[col] = f
		if f.IsPK && m.PK == nil {
			m.PK = f
		}
	}

	// Fall back to a column literally named "id" as the primary key.
	if m.PK == nil {
		if f, ok := m.colByCol["id"]; ok {
			f.IsPK = true
			if isIntKind(idKind(t, f)) {
				f.IsAuto = true
			}
			m.PK = f
		}
	}

	if len(m.Fields) == 0 {
		return nil, fmt.Errorf("prisma: %s has no mapped columns", t.Name())
	}
	return m, nil
}

func idKind(t reflect.Type, f *Field) reflect.Kind {
	return t.FieldByIndex(f.Index).Type.Kind()
}

func buildRelation(sf reflect.StructField, opts tagOptions) (*Relation, error) {
	ft := sf.Type
	many := false
	if ft.Kind() == reflect.Slice {
		many = true
		ft = ft.Elem()
	}
	for ft.Kind() == reflect.Pointer {
		ft = ft.Elem()
	}
	if ft.Kind() != reflect.Struct {
		return nil, fmt.Errorf("relation field must be a struct, pointer or slice of struct")
	}
	if opts.fk == "" {
		return nil, fmt.Errorf("relation requires fk=<column>")
	}
	ref := opts.references
	if ref == "" {
		ref = "id"
	}
	return &Relation{Target: ft, ForeignKey: opts.fk, References: ref, Many: many}, nil
}

type tagOptions struct {
	skip       bool
	pk         bool
	auto       bool
	autoSet    bool
	relation   bool
	col        string
	fk         string
	references string
}

func parseTag(tag string) tagOptions {
	var o tagOptions
	if tag == "" {
		return o
	}
	parts := strings.Split(tag, ",")
	for _, p := range parts {
		p = strings.TrimSpace(p)
		if p == "" {
			continue
		}
		switch {
		case p == "-":
			o.skip = true
		case p == "pk":
			o.pk = true
		case p == "auto":
			o.auto = true
			o.autoSet = true
		case p == "relation":
			o.relation = true
		case strings.HasPrefix(p, "col="):
			o.col = strings.TrimPrefix(p, "col=")
		case strings.HasPrefix(p, "column="):
			o.col = strings.TrimPrefix(p, "column=")
		case strings.HasPrefix(p, "fk="):
			o.fk = strings.TrimPrefix(p, "fk=")
		case strings.HasPrefix(p, "references="):
			o.references = strings.TrimPrefix(p, "references=")
		}
	}
	return o
}

func tableName(t reflect.Type, v any) string {
	if tn, ok := v.(TableNamer); ok {
		return tn.TableName()
	}
	if pv := reflect.New(t); pv.Type().Implements(reflect.TypeOf((*TableNamer)(nil)).Elem()) {
		return pv.Interface().(TableNamer).TableName()
	}
	return pluralize(snakeCase(t.Name()))
}

func pluralize(s string) string {
	if s == "" {
		return s
	}
	if strings.HasSuffix(s, "s") {
		return s
	}
	if strings.HasSuffix(s, "y") {
		return s[:len(s)-1] + "ies"
	}
	return s + "s"
}

// snakeCase converts a CamelCase identifier to snake_case.
func snakeCase(s string) string {
	var b strings.Builder
	runes := []rune(s)
	for i, r := range runes {
		if r >= 'A' && r <= 'Z' {
			if i > 0 && (isLowerOrDigit(runes[i-1]) ||
				(i+1 < len(runes) && runes[i+1] >= 'a' && runes[i+1] <= 'z')) {
				b.WriteByte('_')
			}
			b.WriteRune(r - 'A' + 'a')
		} else {
			b.WriteRune(r)
		}
	}
	return b.String()
}

func isLowerOrDigit(r rune) bool {
	return (r >= 'a' && r <= 'z') || (r >= '0' && r <= '9')
}

func isIntKind(k reflect.Kind) bool {
	switch k {
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
		reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64:
		return true
	}
	return false
}
